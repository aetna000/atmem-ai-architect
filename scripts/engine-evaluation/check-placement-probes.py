"""Run visible placement probes, with two cached-provider checks at a time.

Only init -backend=false, validate and mock-provider plan tests. Generated files
and independent assertion hashes must match before execution. No cloud accounts.
"""
import argparse,concurrent.futures,hashlib,json,re,subprocess,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--packages',type=Path,required=True)
parser.add_argument('--evidence',type=Path,required=True)
args=parser.parse_args()
if args.evidence.exists():parser.error('Preserve prior runs; choose a new evidence directory.')
args.evidence.mkdir(parents=True)
manifest=json.loads((args.packages/'receipt.json').read_text())
def run(case):
    folder=args.packages/case['name']
    for name,digest in case['generatedDigests'].items():
        if hashlib.sha256((folder/name).read_bytes()).hexdigest()!=digest:raise ValueError('Generated bytes changed: '+case['name']+'/'+name)
    for oracle in case['oracles']:
        if hashlib.sha256((folder/oracle['path']).read_bytes()).hexdigest()!=oracle['sha256']:raise ValueError('Independent oracle changed')
    package=folder if case['rootOracle'] or not case['units'] else folder/next(u['path'] for u in case['units'] if u['implementation']=='container-service')
    evidence=args.evidence/case['name']
    result=subprocess.run([sys.executable,str(ROOT/'scripts/engine-evaluation/check-composition-terraform.py'),'--package',str(package),'--terraform',str(ROOT/'.venv/bin/terraform'),'--mirror',str(ROOT/'.local/provider-cache'),'--test','--evidence',str(evidence)],cwd=ROOT,capture_output=True,text=True)
    (args.evidence/(case['name']+'-driver.log')).write_text(result.stdout+result.stderr)
    log=(evidence/'test.log').read_text()if(evidence/'test.log').exists()else''
    count=re.search(r'Success! (\d+) passed, 0 failed\.',log)
    passed=result.returncode==0 and count is not None and int(count[1])>0 and 'independent_'in log
    return {'name':case['name'],'passed':passed,'exitCode':result.returncode,'mockTests':int(count[1])if count else 0,'package':str(package),'oracles':case['oracles']}
with concurrent.futures.ThreadPoolExecutor(max_workers=2)as pool:results=list(pool.map(run,manifest['cases']))
record={'passed':all(r['passed']for r in results),'cases':results,'nativeMockRuns':sum(r['mockTests']for r in results),'boundary':'Current generated configuration, cached native schemas and mock-provider plans. No real cloud read/plan/apply, image runtime or whole-system acceptance.'}
(args.evidence/'summary.json').write_text(json.dumps(record,indent=2)+'\n')
print(json.dumps(record))
raise SystemExit(0 if record['passed']else 1)
