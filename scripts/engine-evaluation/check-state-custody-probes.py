"""Qualify native root configuration with backend disabled; never contact state stores."""
import argparse,concurrent.futures,hashlib,json,subprocess,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--packages',type=Path,required=True);p.add_argument('--evidence',type=Path,required=True);a=p.parse_args()
if a.evidence.exists():p.error('Preserve prior evidence and choose a fresh directory.')
a.evidence.mkdir(parents=True)
def check(case):
 folder=a.packages/case['name']
 for name,digest in case['generatedDigests'].items():
  if hashlib.sha256((folder/name).read_bytes()).hexdigest()!=digest:raise ValueError('Generated bytes changed: '+name)
 config=json.loads((folder/'main.tf.json').read_text())
 expected={'s3':{'encrypt':True,'use_lockfile':True},'azurerm':{'use_azuread_auth':True},'gcs':{},'http':{}}[case['backend']]
 assert config['terraform']['backend']=={case['backend']:expected}
 assert not config['variable']['review_approved']['default']
 assert 'state-custody-and-operations-acceptance-required'in config['locals']['unfinished_work']
 for child in folder.glob('units/*/main.tf.json'):assert 'backend'not in json.loads(child.read_text())['terraform']
 result=subprocess.run([sys.executable,str(ROOT/'scripts/engine-evaluation/check-composition-terraform.py'),'--package',str(folder),'--terraform',str(ROOT/'.venv/bin/terraform'),'--mirror',str(ROOT/'.local/provider-cache'),'--evidence',str(a.evidence/case['name'])],cwd=ROOT,capture_output=True,text=True)
 (a.evidence/(case['name']+'-driver.log')).write_text(result.stdout+result.stderr)
 return {'case':case['name'],'backend':case['backend'],'passed':result.returncode==0,'exitCode':result.returncode}
manifest=json.loads((a.packages/'receipt.json').read_text())
with concurrent.futures.ThreadPoolExecutor(max_workers=2)as pool:results=list(pool.map(check,manifest['cases']))
receipt={'passed':all(r['passed']for r in results),'cases':results,'boundary':'Native init -backend=false and validate only; no backend connection, mock plan, account, locking/recovery, migration, application or deployment acceptance.'}
(a.evidence/'summary.json').write_text(json.dumps(receipt,indent=2)+'\n');print(json.dumps(receipt));raise SystemExit(0 if receipt['passed']else 1)
