import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
import {chromium} from '@playwright/test';
import {toProjectFile,fromProjectFile} from '../src/project-file.mjs';
const base=process.argv[2]||'http://127.0.0.1:5207';
const output=process.argv[3]||'.local/manual-block-ui';
mkdirSync(output,{recursive:true});
const browser=await chromium.launch();
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.setDefaultTimeout(10000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  const project={version:1,revision:1,id:'manual-workflow-fixture',name:'Manual workflow',provider:'tools',nodes:[{id:'system',type:'resource',position:{x:0,y:0},data:{kind:'resource',provider:'tools',label:'Operations'}}],edges:[]};
  await page.locator('#project-file-input').setInputFiles({name:'manual-workflow.atmem-ai-architect.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(toProjectFile(project)))});
  await page.getByText('Project opened.',{exact:true}).waitFor();
  await page.getByLabel('Tools',{exact:true}).getByRole('button',{name:'Add block',exact:true}).click();
  await page.getByRole('button',{name:'Blank block',exact:true}).click();
  const detail=page.getByRole('region',{name:'Block detail'});
  await detail.getByRole('tab',{name:'Overview',exact:true}).click();
  await detail.getByLabel('Block name',{exact:true}).fill('Order intake');
  await detail.getByLabel('Block symbol',{exact:true}).selectOption('database');
  await detail.getByLabel('Description',{exact:true}).fill('Owns order intake.');
  const draft=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('atforma-workspace-v3')));
  const block=(await draft()).nodes.find(n=>n.data.label==='Order intake');
  assert.equal(block.data.symbol,'database');
  assert.equal(fromProjectFile(toProjectFile(await draft())).project.nodes.find(n=>n.id===block.id).data.symbol,'database');
  await detail.getByRole('tab',{name:'Block Spec Kit',exact:true}).click();
  await detail.getByRole('button',{name:'Edit specification',exact:true}).click();
  await detail.getByLabel('Inputs and preconditions',{exact:true}).fill('An order ID and a valid customer reference.');
  await detail.getByRole('button',{name:'Save specification',exact:true}).click();
  await detail.getByRole('button',{name:'Interfaces',exact:true}).click();
  await detail.getByRole('button',{name:'Add interface',exact:true}).click();
  const form=detail.getByRole('form',{name:'New interface',exact:true});
  await form.getByLabel('Other block',{exact:true}).selectOption('system');
  await form.getByLabel('Direction',{exact:true}).selectOption('incoming');
  await form.getByLabel('Interface name',{exact:true}).fill('Submit order');
  await form.getByLabel('Transport and version',{exact:true}).fill('HTTPS v1');
  await form.getByRole('button',{name:'Save interface',exact:true}).click();
  await form.getByRole('alert').waitFor();
  assert.equal((await draft()).edges.length,0);
  for(const [key,value] of Object.entries({transport:'HTTPS v1',input:'Order ID',output:'Receipt ID',authorization:'Operator access',failure:'Retry original order ID',verification:'Repeat key returns one receipt'}))await form.locator('[name='+key+']').fill(value);
  await form.getByRole('button',{name:'Save interface',exact:true}).click();
  const original=(await draft()).edges[0];
  assert.equal(original.source,'system');assert.equal(original.target,block.id);
  await detail.getByText('Operations → Order intake · Submit order',{exact:true}).click();
  await detail.getByRole('button',{name:'Edit interface',exact:true}).click();
  const edit=detail.getByRole('form',{name:'Edit interface',exact:true});
  await edit.getByLabel('Response or result',{exact:true}).fill('Durable receipt ID');
  await edit.getByRole('button',{name:'Save interface',exact:true}).click();
  await page.screenshot({path:output+'/interface.png'});
  const edited=(await draft()).edges[0];assert.equal(edited.id,original.id);assert.equal(edited.interfaceSpec.output,'Durable receipt ID');
  await detail.getByRole('combobox',{name:'Nest under',exact:true}).selectOption('system');
  await detail.getByRole('button',{name:'Back one level'}).click();
  await detail.getByRole('button',{name:'Back one level'}).click();
  await page.keyboard.press('Control+a');
  await page.keyboard.press('Control+c');
  await page.getByLabel('Tools',{exact:true}).getByRole('button',{name:'Paste',exact:true}).click();
  const pasted=await draft();
  assert.equal(pasted.nodes.length,4);assert.equal(pasted.edges.length,2);
  const clone=pasted.nodes.find(n=>n.id!==block.id&&n.data.label==='Order intake');
  assert.equal(clone.data.symbol,'database');
  assert.equal(clone.data.buildSpec.inputs,'An order ID and a valid customer reference.');
  assert.ok(clone.data.parentBlockId&&clone.data.parentBlockId!=='system');
  assert.ok(pasted.edges.some(e=>e.id!==edited.id&&e.source===clone.data.parentBlockId&&e.target===clone.id&&e.interfaceSpec.output==='Durable receipt ID'));
  assert.deepEqual(errors,[]);
  console.log('Manual menu, name/symbol save and reopen, specification, interface creation/edit, and selected subtree paste passed.');
 } catch (error) {
  const page=browser.contexts()[0].pages()[0];
  await page.screenshot({path:output+'/failure.png'});
  console.log((await page.locator('body').innerText()).slice(0,3500));
  throw error;
} finally {await browser.close();}
